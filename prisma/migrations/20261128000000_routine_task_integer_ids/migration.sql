BEGIN;

-- Keep the old list/weekday/slot available while assigning permanent numeric IDs.
ALTER TABLE routine_tasks ADD COLUMN new_id INTEGER GENERATED BY DEFAULT AS IDENTITY;
CREATE TEMP TABLE routine_id_mapping ON COMMIT DROP AS
SELECT list, weekday, list || '-' || slot::text AS old_id, new_id
FROM routine_tasks;

-- A streak must keep pointing to exactly the same morning/night routine.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM planner_days d
    WHERE jsonb_typeof(d.checks) <> 'array'
       OR EXISTS (
         SELECT 1 FROM jsonb_array_elements(
           CASE WHEN jsonb_typeof(d.checks) = 'array' THEN d.checks ELSE '[]'::jsonb END
         ) AS item(value)
         WHERE jsonb_typeof(item.value) <> 'string'
       )
  ) THEN
    RAISE EXCEPTION 'Cannot migrate malformed planner task checks.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM achievements a
    WHERE a.tracking = 'streak'
      AND NOT EXISTS (
        SELECT 1 FROM routine_id_mapping m
        WHERE m.old_id = a.task_id AND m.weekday = -1
      )
  ) THEN
    RAISE EXCEPTION 'Cannot migrate an achievement with an unknown routine task ID.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM planner_days d
    CROSS JOIN LATERAL jsonb_array_elements_text(d.checks) AS c(task_id)
    JOIN routine_id_mapping m ON c.task_id = m.new_id::text
  ) THEN
    RAISE EXCEPTION 'Cannot migrate checks that already contain numeric task IDs.';
  END IF;
END $$;

UPDATE achievements a
SET task_id = m.new_id::text
FROM routine_id_mapping m
WHERE a.tracking = 'streak' AND a.task_id = m.old_id AND m.weekday = -1;

-- Daily IDs were reused across weekdays, so each day's date selects the right row.
UPDATE planner_days d
SET checks = COALESCE((
  SELECT jsonb_agg(COALESCE(m.new_id::text, c.task_id) ORDER BY c.ordinality)
  FROM jsonb_array_elements_text(d.checks) WITH ORDINALITY AS c(task_id, ordinality)
  LEFT JOIN routine_id_mapping m ON m.old_id = c.task_id
    AND (m.weekday = -1 OR m.weekday = extract(isodow FROM d.day)::integer - 1)
), '[]'::jsonb);

-- Preserve unknown historical keys rather than silently deleting ledger entries.
UPDATE point_ledger p
SET task_key = 'builtin:' || p.task_date::text || ':' || m.new_id::text
FROM routine_id_mapping m
WHERE p.entry_type = 'earn'
  AND p.task_date IS NOT NULL
  AND p.task_key = 'builtin:' || p.task_date::text || ':' || m.old_id
  AND (m.weekday = -1 OR m.weekday = extract(isodow FROM p.task_date)::integer - 1);

ALTER TABLE routine_tasks DROP CONSTRAINT routine_tasks_pkey;
DROP INDEX routine_tasks_list_weekday_slot_key;
ALTER TABLE routine_tasks DROP COLUMN id, DROP COLUMN slot;
ALTER TABLE routine_tasks RENAME COLUMN new_id TO id;
ALTER TABLE routine_tasks ADD CONSTRAINT routine_tasks_pkey PRIMARY KEY (id);

COMMIT;
